//! Generation drivers (stage 4). The worker never runs the model in its own process: it hands
//! the approved spec to an isolated sandbox and takes back a patch, the full transcript and the
//! cost. Keys stay outside the sandbox (see deploy/sandbox/README.md).

use chrono::{SecondsFormat, Utc};
use std::path::PathBuf;
use std::time::Duration;
use trailhead_core::spec::Spec;

use crate::config::{Config, SandboxDriver};

pub struct Generated {
    pub base: String,
    pub patch: Vec<u8>,
    pub transcript: Vec<u8>,
    pub cost_credits: i64,
    pub run_id: String,
    pub image: String,
    pub started_at: String,
    pub finished_at: String,
}

/// The exact instruction given to the pinned model. It is published in the ledger verbatim.
pub fn generation_prompt(intent_id: i64, spec: &Spec, repo: &str, workspace_dir: &str) -> String {
    let ws = if workspace_dir.trim().is_empty() || workspace_dir == "." {
        "the repository root".to_string()
    } else {
        format!("`{}/`", workspace_dir.trim_end_matches('/'))
    };
    format!(
        "You are implementing Trailhead intent #{intent_id} in the {repo} repository (Rust).\n\
         The Cargo workspace is in {ws}. Run cargo commands from there.\n\
         Implement exactly the approved spec below: every requirement, nothing more.\n\
         Rules: do not modify tests/, fuzz/, sim/, proptest-regressions/, .github/, gates/, build.rs, Cargo.toml dependencies or Cargo.lock;\n\
         add new tests for each acceptance test under the crate's own src (#[cfg(test)]) or tests/ only if the spec says so;\n\
         no network calls outside net/, no unsafe, no new dependencies, no telemetry, no reading secrets or environment variables.\n\
         This machine is offline: every dependency in Cargo.lock is already downloaded; do not try to fetch anything.\n\
         Run `cargo build`, `cargo clippy -- -D warnings` and `cargo test` until they pass. Keep the change small.\n\n\
         APPROVED SPEC (JSON):\n{}\n",
        serde_json::to_string_pretty(spec).unwrap_or_default()
    )
}

fn now() -> String {
    Utc::now().to_rfc3339_opts(SecondsFormat::Secs, true)
}

fn dry_run_patch(intent_id: i64, spec: &Spec) -> Vec<u8> {
    let body = format!(
        "# Intent #{intent_id}: {}\n\nGenerated by the Trailhead dry-run driver: no model was called.\n\n```json\n{}\n```\n",
        spec.title.clone().unwrap_or_default(),
        serde_json::to_string_pretty(spec).unwrap_or_default()
    );
    let lines: Vec<&str> = body.lines().collect();
    let path = format!("docs/intents/{intent_id}.md");
    let mut p = format!(
        "diff --git a/{path} b/{path}\nnew file mode 100644\n--- /dev/null\n+++ b/{path}\n@@ -0,0 +1,{} @@\n",
        lines.len()
    );
    for l in lines {
        p.push('+');
        p.push_str(l);
        p.push('\n');
    }
    p.into_bytes()
}

pub async fn generate(cfg: &Config, intent_id: i64, spec: &Spec) -> anyhow::Result<Generated> {
    let run_id = format!("run-{}", uuid::Uuid::new_v4());
    let prompt = generation_prompt(intent_id, spec, &cfg.target_repo, &cfg.workspace_dir);
    let started_at = now();
    match &cfg.sandbox {
        SandboxDriver::DryRun => {
            let transcript = serde_json::json!({
                "type": "result", "driver": "dry-run", "model": cfg.agent.generation.model_id,
                "note": "no model call; patch documents the approved spec", "prompt": prompt
            })
            .to_string()
            .into_bytes();
            Ok(Generated {
                base: "dry-run".into(),
                patch: dry_run_patch(intent_id, spec),
                transcript,
                cost_credits: 0,
                run_id,
                image: "dry-run".into(),
                started_at: started_at.clone(),
                finished_at: now(),
            })
        }
        SandboxDriver::Command(cmd) => {
            let dir: PathBuf = cfg.work_dir.join(&run_id);
            tokio::fs::create_dir_all(dir.join("out")).await?;
            tokio::fs::write(dir.join("spec.json"), serde_json::to_vec_pretty(spec)?).await?;
            tokio::fs::write(dir.join("prompt.md"), &prompt).await?;
            let g = &cfg.agent.generation;
            let mut child = tokio::process::Command::new("sh")
                .arg("-c")
                .arg(cmd)
                .env("TRAILHEAD_RUN_DIR", &dir)
                .env("TRAILHEAD_RUN_ID", &run_id)
                .env("TRAILHEAD_INTENT_ID", intent_id.to_string())
                .env("TRAILHEAD_MODEL_ID", &g.model_id)
                .env("TRAILHEAD_MAX_BUDGET_USD", g.max_budget_usd.to_string())
                .env("TRAILHEAD_MAX_TURNS", g.max_turns.to_string())
                .env("TRAILHEAD_ALLOWED_TOOLS", g.allowed_tools.join(","))
                .env("TRAILHEAD_TARGET_REPO", &cfg.target_repo)
                .env("TRAILHEAD_WORKSPACE_DIR", &cfg.workspace_dir)
                .kill_on_drop(true)
                .spawn()?;
            let status =
                tokio::time::timeout(Duration::from_secs(g.wall_clock_minutes * 60), child.wait())
                    .await
                    .map_err(|_| {
                        anyhow::anyhow!("sandbox run exceeded {} minutes", g.wall_clock_minutes)
                    })??;
            if !status.success() {
                anyhow::bail!("sandbox run failed with {status}");
            }
            let out = dir.join("out");
            let read = |n: &str| std::fs::read(out.join(n));
            let patch =
                read("patch").map_err(|e| anyhow::anyhow!("sandbox produced no patch: {e}"))?;
            if patch.is_empty() {
                anyhow::bail!("sandbox produced an empty patch");
            }
            let cost_usd: f64 = read("cost_usd")
                .ok()
                .and_then(|b| String::from_utf8(b).ok())
                .and_then(|s| s.trim().parse().ok())
                .unwrap_or(0.0);
            Ok(Generated {
                base: String::from_utf8(read("base")?)?.trim().to_string(),
                patch,
                transcript: read("transcript.jsonl").unwrap_or_default(),
                cost_credits: (cost_usd * 100.0).ceil() as i64,
                run_id,
                image: read("image_digest")
                    .ok()
                    .and_then(|b| String::from_utf8(b).ok())
                    .unwrap_or_default()
                    .trim()
                    .to_string(),
                started_at,
                finished_at: now(),
            })
        }
    }
}
